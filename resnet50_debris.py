def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        print(f"\nNo rows to write: {path}")
        return

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    print(f"\nSaved: {path}")


def best_f1_row_per_split(epoch_results: list[dict]) -> list[dict]:
    """One row per train_frac: the epoch with the highest test F1."""

    best: dict[float, dict] = {}

    for row in epoch_results:
        frac = row["train_frac"]
        prev = best.get(frac)

        if prev is None:
            best[frac] = row
            continue

        better_f1 = row["test_f1"] > prev["test_f1"]
        same_f1_lower_fpr = (
            row["test_f1"] == prev["test_f1"]
            and row["test_fpr"] < prev["test_fpr"]
        )

        if better_f1 or same_f1_lower_fpr:
            best[frac] = row

    return [best[frac] for frac in sorted(best)]


