# copying the originals.
# ============================================================

def write_split(
    train,
    test,
    train_name: str,
    test_name: str,
    target_size: tuple[int, int],
) -> None:

    # Re-create output folders
    for parent in (YES_DIR, NO_DIR):

        for name in (train_name, test_name):

            dest = parent / name

            if dest.exists():
                shutil.rmtree(dest)

            dest.mkdir(
                parents=True,
                exist_ok=True,
            )

    # Process and save images
    for split_name, pairs in (
        (train_name, train),
        (test_name, test),
    ):

        for path, lab in pairs:

            dest_dir = (
                YES_DIR
                if lab == 1
                else NO_DIR
            ) / split_name

            # Load original
            img = load_gray(path)

            # NEW:
            # resize to uniform resolution
            # + Gaussian blur
            img = preprocess_image(
                img,
                target_size,
            )

            dest_path = dest_dir / path.name

            ok = cv2.imwrite(
                str(dest_path),
                img,
            )

            if not ok:
                raise IOError(
                    f"Could not save {dest_path}"
                )

    print(
        f"\nwrote processed images:\n"
        f"{YES_DIR / train_name}\n"
        f"{YES_DIR / test_name}\n"
        f"{NO_DIR / train_name}\n"
        f"{NO_DIR / test_name}"
    )

