def list_images(folder: Path) -> list[Path]:

    if not folder.exists():
        raise FileNotFoundError(
            f"Folder does not exist: {folder}"
        )

    return sorted(
        p
        for p in folder.iterdir()
        if p.is_file()
        and p.suffix.lower() in IMAGE_EXTENSIONS
    )


class DebrisDataset(Dataset):
    """
    Binary debris classification.

    label:
        0 = no debris
        1 = debris
    """

    def __init__(
        self,
        yes_dir: Path | None = None,
        no_dir: Path | None = None,
        transform=None,
        samples: list[tuple[Path, int]] | None = None,
    ):

        self.transform = transform

        if samples is not None:
            self.samples = list(samples)
            n_yes = sum(lab == 1 for _, lab in self.samples)
            n_no = sum(lab == 0 for _, lab in self.samples)
        else:
            if yes_dir is None or no_dir is None:
                raise ValueError(
                    "yes_dir and no_dir are required "
                    "when samples is not given"
                )

            yes_images = list_images(yes_dir)
            no_images = list_images(no_dir)

            self.samples = (
                [(p, 1) for p in yes_images]
                + [(p, 0) for p in no_images]
            )
            n_yes = len(yes_images)
            n_no = len(no_images)

        if not self.samples:
            raise RuntimeError(
                "No images found for dataset"
            )

        print(
            f"\nDataset:"
            f"\n  debris     = {n_yes}"
            f"\n  no debris  = {n_no}"
            f"\n  total      = {len(self.samples)}"
        )

    def __len__(self):

        return len(self.samples)

    def __getitem__(self, index):

        path, label = self.samples[index]

        # ResNet expects RGB / 3 channels.
        image = Image.open(path).convert("RGB")

        if self.transform is not None:
            image = self.transform(image)

        return image, label


# ============================================================
# Transform
# ============================================================

def build_transforms():

    # ImageNet normalization used for pretrained ResNet-50.
    normalize = transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225],
    )

    # --------------------------------------------------------
    # Training
    #
    # Keep augmentation conservative because small debris
    # structures may be important.
    # --------------------------------------------------------

    train_transform = transforms.Compose(
        [
            transforms.Resize(
                (MODEL_INPUT_SIZE, MODEL_INPUT_SIZE)
            ),

            transforms.RandomHorizontalFlip(
                p=0.5
            ),

            transforms.ToTensor(),

            normalize,
        ]
    )

    # --------------------------------------------------------
    # Test
    #
    # No random augmentation.
    # --------------------------------------------------------

    test_transform = transforms.Compose(
        [
            transforms.Resize(
                (MODEL_INPUT_SIZE, MODEL_INPUT_SIZE)
            ),

            transforms.ToTensor(),

            normalize,
        ]
    )

    return train_transform, test_transform


# ============================================================
# Model
# ============================================================

def build_model() -> nn.Module:

    # Pretrained ImageNet ResNet-50
    weights = ResNet50_Weights.DEFAULT

    model = models.resnet50(
        weights=weights
    )

    # Original:
    #
    # model.fc = Linear(2048, 1000)
    #
    # Replace with binary classification head:
    #
    # class 0 = no debris
    # class 1 = debris

    in_features = model.fc.in_features

    model.fc = nn.Linear(
        in_features,
        2,
    )

    return model


# ============================================================
# Metrics
# ============================================================

def compute_metrics(
    pred: np.ndarray,
    y: np.ndarray,
):

    tp = int(
        np.sum(
            (pred == 1) & (y == 1)
        )
    )

    fp = int(
        np.sum(
            (pred == 1) & (y == 0)
        )
    )

    tn = int(
        np.sum(
            (pred == 0) & (y == 0)
        )
    )

    fn = int(
        np.sum(
            (pred == 0) & (y == 1)
        )
    )

    accuracy = (
        (tp + tn) / len(y)
        if len(y)
        else 0.0
    )

    precision = (
        tp / (tp + fp)
        if tp + fp
        else 0.0
    )

    recall = (
        tp / (tp + fn)
        if tp + fn
        else 0.0
    )

    fpr = (
        fp / (fp + tn)
        if fp + tn
        else 0.0
    )

    f1 = (
        2 * precision * recall
        / (precision + recall)
        if precision + recall
        else 0.0
    )

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "fpr": fpr,
        "f1": f1,
        "tp": tp,
        "fp": fp,
        "tn": tn,
        "fn": fn,
    }


# ============================================================
# Train one epoch
# ============================================================

def train_one_epoch(
    model,
    loader,
    criterion,
    optimizer,
    device,
):

    model.train()

    running_loss = 0.0

    all_pred = []
    all_y = []

    for images, labels in loader:

        images = images.to(device)
        labels = labels.to(device)

        # ---------------------------------------------
        # Clear gradients
        # ---------------------------------------------

        optimizer.zero_grad()

        # ---------------------------------------------
        # Forward
        # ---------------------------------------------

        logits = model(images)

        loss = criterion(
            logits,
            labels,
        )

        # ---------------------------------------------
        # Backward
        # ---------------------------------------------

        loss.backward()

        # ---------------------------------------------
        # Update weights
        # ---------------------------------------------

        optimizer.step()

        running_loss += (
            loss.item()
            * images.size(0)
        )

        pred = torch.argmax(
            logits,
            dim=1,
        )

        all_pred.extend(
            pred.detach().cpu().numpy()
        )

        all_y.extend(
            labels.detach().cpu().numpy()
        )

    epoch_loss = (
        running_loss
        / len(loader.dataset)
    )

    metrics = compute_metrics(
        np.array(all_pred),
        np.array(all_y),
    )

    return epoch_loss, metrics


# ============================================================
# Evaluation
# ============================================================

@torch.no_grad()
def evaluate(
    model,
    loader,
    criterion,
    device,
):

    model.eval()

    running_loss = 0.0

    all_pred = []
    all_y = []

    for images, labels in loader:

        images = images.to(device)
        labels = labels.to(device)

        logits = model(images)

        loss = criterion(
            logits,
            labels,
        )

        running_loss += (
            loss.item()
            * images.size(0)
        )

        pred = torch.argmax(
            logits,
            dim=1,
        )

        all_pred.extend(
            pred.cpu().numpy()
        )

        all_y.extend(
            labels.cpu().numpy()
        )

    epoch_loss = (
        running_loss
        / len(loader.dataset)
    )

    metrics = compute_metrics(
        np.array(all_pred),
        np.array(all_y),
    )

    return epoch_loss, metrics

